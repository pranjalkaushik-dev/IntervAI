import React, { useEffect, useState } from 'react';
import { useParams, useNavigate } from 'react-router-dom';
import { ArrowLeft, FileText, ShieldCheck, Code2, Brain, MessageCircle } from 'lucide-react';
import reportApi from '../api/reportApi';

export default function InterviewReportPage() {
  const { id } = useParams();
  const navigate = useNavigate();
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    reportApi.getReport(id)
      .then((response) => setData(response.data))
      .catch((err) => setError(err?.response?.data?.message || err.message))
      .finally(() => setLoading(false));
  }, [id]);

  if (loading) return <div className="ia-page"><div className="ia-card ia-empty">Loading report…</div></div>;
  if (error) return <div className="ia-page"><div className="ia-error">{error}</div></div>;

  const report = data?.report;
  return (
    <div className="ia-page">
      <div className="ia-page-head">
        <div>
          <button className="ia-outline-btn" onClick={() => navigate('/dashboard')}><ArrowLeft size={14} /> Dashboard</button>
          <h1 style={{ marginTop: 12 }}>Interview Performance Report</h1>
          <p>{data?.interview?.title || 'Completed interview'}</p>
        </div>
      </div>

      {!report ? (
        <div className="ia-card ia-empty">
          <FileText size={30} />
          <b>Report not generated yet</b>
          <span>The company can generate the report after the interview.</span>
        </div>
      ) : (
        <>
          <div className="ia-kpis">
            <KPI value={report.overallScore} label="Overall" icon={Brain} />
            <KPI value={report.technicalScore} label="Technical" icon={Brain} />
            <KPI value={report.codingScore} label="Coding" icon={Code2} />
            <KPI value={report.communicationScore} label="Communication" icon={MessageCircle} />
          </div>

          <div className="ia-card">
            <h3>Measured performance</h3>
            <div className="ia-integrity-grid">
              <div><b>{report.testsPassed}/{report.testsTotal}</b><span>Tests passed</span></div>
              <div><b>{report.submissions}</b><span>Submissions</span></div>
              <div><b>{report.questionsAnswered}</b><span>Evaluated answers</span></div>
              <div><b>{report.violations}</b><span>Integrity events</span></div>
            </div>
          </div>

          <div className="ia-dashboard-bottom">
            <div className="ia-card mini">
              <h3>Strengths</h3>
              {(report.strengths || []).map((item, index) => <p key={index}>• {item}</p>)}
            </div>
            <div className="ia-card mini">
              <h3>Improvement areas</h3>
              {(report.improvements || []).map((item, index) => <p key={index}>• {item}</p>)}
            </div>
          </div>

          <div className="ia-card">
            <div className="ia-card-head">
              <h3>{report.aiSummaryStatus === 'COMPLETED' ? 'AI summary' : 'Metrics-based summary'}</h3>
              <ShieldCheck size={18} />
            </div>
            <p role="status" className="text-xs text-slate-500 mb-2">
              {report.aiSummaryStatus === 'COMPLETED'
                ? 'Generated by the configured Gemini model from recorded interview measurements.'
                : 'AI summary unavailable; this text is derived from recorded interview measurements.'}
            </p>
            <p className="text-sm text-slate-700 leading-relaxed">{report.aiSummary}</p>
          </div>
        </>
      )}
    </div>
  );
}

function KPI({ value, label, icon: Icon }) {
  return (
    <div className="ia-kpi blue">
      <div><span>{label}</span><b>{value}/100</b></div>
      <i><Icon size={19} /></i>
    </div>
  );
}
